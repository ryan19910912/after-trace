import { sql } from 'drizzle-orm';
import {
  bigint,
  bigserial,
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  varchar,
} from 'drizzle-orm/pg-core';
import { worklogUsers } from './schema-worklog';

export const worklogNotificationTypeEnum = pgEnum('worklog_notification_type', [
  'ANNOUNCEMENT',
  'SYSTEM',
  'TASK',
]);

export const worklogNotificationStatusEnum = pgEnum('worklog_notification_status', [
  'DRAFT',
  'SCHEDULED',
  'SENDING',
  'SENT',
  'CANCELLED',
  'FAILED',
]);

export const worklogNotificationAudienceEnum = pgEnum('worklog_notification_audience', [
  'ALL_USERS',
  'FREE_USERS',
  'AI_SUBSCRIBERS',
  'SPECIFIC_USERS',
]);

export const worklogNotificationDeliveryStatusEnum = pgEnum(
  'worklog_notification_delivery_status',
  ['PENDING', 'SENT', 'FAILED', 'SKIPPED'],
);

/**
 * One logical notification authored by Admin or generated by a deterministic domain event.
 * Category is independent from delivery channel. IN_APP is represented durably by recipient
 * rows; PUSH is an optional delivery on top of that durable recipient state.
 */
export const worklogNotifications = pgTable(
  'worklog_notifications',
  {
    id: bigserial('id', { mode: 'number' }).primaryKey(),
    type: worklogNotificationTypeEnum('type').notNull(),
    status: worklogNotificationStatusEnum('status').default('DRAFT').notNull(),
    audience: worklogNotificationAudienceEnum('audience').notNull(),
    title: varchar('title', { length: 255 }).notNull(),
    body: text('body').notNull(),
    inAppEnabled: boolean('in_app_enabled').default(true).notNull(),
    pushEnabled: boolean('push_enabled').default(false).notNull(),
    systemEventKey: varchar('system_event_key', { length: 255 }),
    referenceType: varchar('reference_type', { length: 64 }),
    referenceId: bigint('reference_id', { mode: 'number' }),
    deepLink: text('deep_link'),
    metadata: jsonb('metadata'),
    createdByActor: varchar('created_by_actor', { length: 128 }),
    scheduledAt: timestamp('scheduled_at', { withTimezone: true }),
    dispatchStartedAt: timestamp('dispatch_started_at', { withTimezone: true }),
    sentAt: timestamp('sent_at', { withTimezone: true }),
    cancelledAt: timestamp('cancelled_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (table) => [
    uniqueIndex('worklog_notification_system_event_key_uq').on(table.systemEventKey),
    index('worklog_notification_status_schedule_idx').on(table.status, table.scheduledAt),
    index('worklog_notification_type_created_idx').on(table.type, table.createdAt),
    check(
      'worklog_notification_channel_ck',
      sql`${table.inAppEnabled} = TRUE OR ${table.pushEnabled} = TRUE`,
    ),
    check(
      'worklog_notification_schedule_ck',
      sql`${table.status} <> 'SCHEDULED' OR ${table.scheduledAt} IS NOT NULL`,
    ),
  ],
);

/**
 * Durable per-user notification state. This is also the authoritative IN_APP notification
 * center row and carries idempotent push-delivery state for that recipient.
 *
 * push_attempt_count is a compare-and-set generation as well as an operator metric. A worker
 * increments it only when claiming a PENDING recipient. Completion/reschedule operations must
 * match that generation so a stale worker cannot overwrite a newer retry result.
 */
export const worklogNotificationRecipients = pgTable(
  'worklog_notification_recipients',
  {
    id: bigserial('id', { mode: 'number' }).primaryKey(),
    notificationId: bigint('notification_id', { mode: 'number' })
      .notNull()
      .references(() => worklogNotifications.id, { onDelete: 'cascade' }),
    userId: bigint('user_id', { mode: 'number' })
      .notNull()
      .references(() => worklogUsers.id, { onDelete: 'cascade' }),
    readAt: timestamp('read_at', { withTimezone: true }),
    pushStatus: worklogNotificationDeliveryStatusEnum('push_status').default('PENDING').notNull(),
    pushAttemptCount: integer('push_attempt_count').default(0).notNull(),
    pushAttemptedAt: timestamp('push_attempted_at', { withTimezone: true }),
    pushNextAttemptAt: timestamp('push_next_attempt_at', { withTimezone: true }),
    pushSentAt: timestamp('push_sent_at', { withTimezone: true }),
    pushFailureCode: varchar('push_failure_code', { length: 128 }),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (table) => [
    uniqueIndex('worklog_notification_recipient_uq').on(table.notificationId, table.userId),
    index('worklog_notification_recipient_user_read_idx').on(table.userId, table.readAt, table.createdAt),
    index('worklog_notification_recipient_push_idx').on(table.pushStatus, table.pushNextAttemptAt, table.pushAttemptedAt),
    check('worklog_notification_recipient_push_attempt_count_ck', sql`${table.pushAttemptCount} >= 0`),
  ],
);

/**
 * Web Push subscription per browser/PWA installation. These rows are delivery endpoints,
 * never account identity. Invalid endpoints can be revoked independently from the user.
 */
export const worklogPushSubscriptions = pgTable(
  'worklog_push_subscriptions',
  {
    id: bigserial('id', { mode: 'number' }).primaryKey(),
    userId: bigint('user_id', { mode: 'number' })
      .notNull()
      .references(() => worklogUsers.id, { onDelete: 'cascade' }),
    endpoint: text('endpoint').notNull(),
    p256dh: text('p256dh').notNull(),
    auth: text('auth').notNull(),
    userAgent: text('user_agent'),
    platform: varchar('platform', { length: 64 }),
    revokedAt: timestamp('revoked_at', { withTimezone: true }),
    lastSuccessAt: timestamp('last_success_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (table) => [
    uniqueIndex('worklog_push_subscription_endpoint_uq').on(table.endpoint),
    index('worklog_push_subscription_user_active_idx').on(table.userId, table.revokedAt),
  ],
);

/**
 * Small, user-controlled push preference set. Durable IN_APP SYSTEM notifications remain
 * independent from these push switches.
 */
export const worklogNotificationPreferences = pgTable('worklog_notification_preferences', {
  userId: bigint('user_id', { mode: 'number' })
    .primaryKey()
    .references(() => worklogUsers.id, { onDelete: 'cascade' }),
  announcementPushEnabled: boolean('announcement_push_enabled').default(true).notNull(),
  systemPushEnabled: boolean('system_push_enabled').default(true).notNull(),
  taskPushEnabled: boolean('task_push_enabled').default(true).notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
});
